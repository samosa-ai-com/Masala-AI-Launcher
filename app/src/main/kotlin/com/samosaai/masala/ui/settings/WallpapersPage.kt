/** One bundled wallpaper from `assets/wallpapers/catalog.json`. */
@Serializable
private data class BundledWallpaper(
    val file: String,
    val title: String,
    val category: String,
    val tags: List<String> = emptyList(),
)

private sealed interface CatalogItem {
    data object Device : CatalogItem
    data class Bundled(val w: BundledWallpaper) : CatalogItem
    data class Generated(val w: Wallpaper) : CatalogItem
}

/**
 * Settings → Wallpapers (plan `docs/plans/wallpaper-catalog.md`): bundled premium wallpapers
 * with category filters, the user's generated ones (searchable by prompt), a From-device tile,
 * and Generate with AI (opens home chat with a wallpaper prefill). The same screen the home
 * long-press "Change wallpaper" opens.
 */
@Composable
fun WallpapersPage(onBack: () -> Unit, onGenerateWithAI: () -> Unit) {
    val context = LocalContext.current
    val app = context.masala
    val store = app.wallpapers
    val scope = rememberCoroutineScope()
    var query by rememberSaveable { mutableStateOf("") }
    var chip by rememberSaveable { mutableStateOf("") }
    var generated by remember { mutableStateOf<List<Wallpaper>>(emptyList()) }
    var nonce by remember { mutableIntStateOf(0) }
    var bundled by remember { mutableStateOf<List<BundledWallpaper>>(emptyList()) }
    var pickedGenerated by remember { mutableStateOf<Wallpaper?>(null) }
    var pickedBundled by remember { mutableStateOf<BundledWallpaper?>(null) }
    var pickedDeviceUri by remember { mutableStateOf<Uri?>(null) }
    var confirmDelete by remember { mutableStateOf<Wallpaper?>(null) }

    LaunchedEffect(Unit) {
        bundled = withContext(Dispatchers.IO) { loadBundled(context) }
    }
    LaunchedEffect(query, nonce) {
        generated = withContext(Dispatchers.IO) { store.search(query) }
    }

    val deletedText = stringResource(R.string.wallpaper_deleted)
    fun toast(text: String) = Toast.makeText(context, text, Toast.LENGTH_LONG).show()

    val devicePicker = rememberLauncherForActivityResult(ActivityResultContracts.GetContent()) { uri: Uri? ->
        if (uri != null) pickedDeviceUri = uri
    }

    val categories = remember(bundled) { bundled.map { it.category }.distinct() }
    val q = query.trim().lowercase()
    fun matchesBundled(w: BundledWallpaper): Boolean {
        if (chip.isNotEmpty() && chip != "generated" && !w.category.equals(chip, ignoreCase = true)) return false
        if (chip == "generated") return false
        if (q.isEmpty()) return true
        return w.title.lowercase().contains(q) || w.category.lowercase().contains(q) || w.tags.any { it.lowercase().contains(q) }
    }
    val shownBundled = bundled.filter(::matchesBundled)
    val shownGenerated = if (chip.isNotEmpty() && chip != "generated") emptyList() else generated
    val items = buildList {
        if (chip.isEmpty() && q.isEmpty()) add(CatalogItem.Device)
        addAll(shownBundled.map { CatalogItem.Bundled(it) })
        addAll(shownGenerated.map { CatalogItem.Generated(it) })
    }

    SettingsScaffold(stringResource(R.string.wallpaper_title), onBack) {
        OutlinedTextField(
            query, { query = it },
            placeholder = { Text(stringResource(R.string.wallpaper_search_hint)) },
            singleLine = true,
            modifier = Modifier.fillMaxWidth(),
        )
        OutlinedButton(onClick = onGenerateWithAI, modifier = Modifier.fillMaxWidth()) {
            Icon(Icons.Rounded.AutoFixHigh, null)
            Text(stringResource(R.string.wallpaper_generate_ai), modifier = Modifier.padding(start = 8.dp))
        }
        Row(Modifier.horizontalScroll(rememberScrollState()), horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            FilterChip(selected = chip.isEmpty(), onClick = { chip = "" }, label = { Text(stringResource(R.string.wallpaper_chip_all)) })
            categories.forEach { c ->
                FilterChip(selected = chip.equals(c, ignoreCase = true), onClick = { chip = c }, label = { Text(c.replaceFirstChar { it.uppercase() }) })
            }
            FilterChip(selected = chip == "generated", onClick = { chip = "generated" }, label = { Text(stringResource(R.string.wallpaper_chip_generated)) })
        }
        if (items.isEmpty()) {
            Text(
                stringResource(R.string.wallpaper_empty),
                style = MaterialTheme.typography.bodyMedium,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
                modifier = Modifier.padding(vertical = 24.dp),
            )
        } else {
            LazyVerticalGrid(
                columns = GridCells.Fixed(2),
                modifier = Modifier.weight(1f).fillMaxWidth(),
                verticalArrangement = Arrangement.spacedBy(10.dp),
                horizontalArrangement = Arrangement.spacedBy(10.dp),
            ) {
                items(items, key = { itemKey(it) }) { item ->
                    when (item) {
                        is CatalogItem.Device -> DeviceTile { devicePicker.launch("image/*") }
                        is CatalogItem.Bundled -> Column(Modifier.clip(RoundedCornerShape(14.dp)).clickable { pickedBundled = item.w }) {
                            WallpaperThumb(thumbKey = "asset:${item.w.file}", load = { decodeAssetThumb(context, item.w.file, 540) }, Modifier.fillMaxWidth().aspectRatio(9f / 16f))
                            Text(
                                item.w.title, style = MaterialTheme.typography.labelSmall,
                                color = MaterialTheme.colorScheme.onSurfaceVariant,
                                maxLines = 2, overflow = TextOverflow.Ellipsis,
                                modifier = Modifier.padding(horizontal = 4.dp, vertical = 6.dp),
                            )
                        }
                        is CatalogItem.Generated -> Column(Modifier.clip(RoundedCornerShape(14.dp)).clickable { pickedGenerated = item.w }) {
                            WallpaperThumb(thumbKey = item.w.file.absolutePath, load = { decodeFileThumb(item.w.file.absolutePath, 540) }, Modifier.fillMaxWidth().aspectRatio(9f / 16f))
                            Text(
                                item.w.prompt.ifBlank { item.w.file.name }, style = MaterialTheme.typography.labelSmall,
                                color = MaterialTheme.colorScheme.onSurfaceVariant,
                                maxLines = 2, overflow = TextOverflow.Ellipsis,
                                modifier = Modifier.padding(horizontal = 4.dp, vertical = 6.dp),
                            )
                        }
                    }
                }
            }
        }
    }

    pickedGenerated?.let { w ->
        WallpaperDialog(
            title = w.prompt.ifBlank { w.file.name },
            thumbKey = w.file.absolutePath,
            loadThumb = { decodeFileThumb(w.file.absolutePath, 1080) },
            onSet = { target ->
                pickedGenerated = null
                scope.launch { toast(app.wallpaperTool.setWallpaper(w.file.absolutePath, target).message) }
            },
            onExtra = {
                TextButton(onClick = {
                    pickedGenerated = null
                    scope.launch { toast(app.wallpaperTool.saveToGallery(w.file.absolutePath).message) }
                }) { Text(stringResource(R.string.result_save)) }
                TextButton(onClick = { confirmDelete = w; pickedGenerated = null }) { Text(stringResource(R.string.wallpaper_delete)) }
            },
            onDismiss = { pickedGenerated = null },
        )
    }

    pickedBundled?.let { w ->
        val cacheFile = remember(w.file) { File(context.cacheDir, "bundled-${w.file}").also { runCatching { context.assets.open("wallpapers/${w.file}").use { input -> it.outputStream().use { out -> input.copyTo(out) } } } } }
        WallpaperDialog(
            title = w.title,
            thumbKey = "asset:${w.file}",
            loadThumb = { decodeAssetThumb(context, w.file, 1080) },
            onSet = { target ->
                pickedBundled = null
                scope.launch { toast(app.wallpaperTool.setWallpaper(cacheFile.absolutePath, target).message) }
            },
            onExtra = {
                TextButton(onClick = {
                    pickedBundled = null
                    scope.launch { toast(app.wallpaperTool.saveToGallery(cacheFile.absolutePath).message) }
                }) { Text(stringResource(R.string.result_save)) }
            },
            onDismiss = { pickedBundled = null },
        )
    }

    pickedDeviceUri?.let { uri ->
        WallpaperDialog(
            title = stringResource(R.string.home_menu_wallpaper),
            thumbKey = uri.toString(),
            loadThumb = { decodeUriThumb(context, uri, 1080) },
            onSet = { target ->
                pickedDeviceUri = null
                scope.launch { toast(app.wallpaperTool.setWallpaper(uri.toString(), target).message) }
            },
            onExtra = {},
            onDismiss = { pickedDeviceUri = null },
        )
    }

    confirmDelete?.let { w ->
        AlertDialog(
            onDismissRequest = { confirmDelete = null },
            title = { Text(stringResource(R.string.wallpaper_delete_title)) },
            text = { Text(w.prompt.ifBlank { w.file.name }, maxLines = 3, overflow = TextOverflow.Ellipsis) },
            confirmButton = {
                TextButton(onClick = {
                    confirmDelete = null
                    scope.launch {
                        withContext(Dispatchers.IO) { store.delete(w.id) }
                        nonce++
                        toast(deletedText)
                    }
                }) { Text(stringResource(R.string.wallpaper_delete)) }
            },
            dismissButton = { TextButton(onClick = { confirmDelete = null }) { Text(stringResource(R.string.command_close)) } },
        )
    }
}

private fun itemKey(item: CatalogItem): String = when (item) {
    is CatalogItem.Device -> "device"
    is CatalogItem.Bundled -> "bundled:${item.w.file}"
    is CatalogItem.Generated -> "generated:${item.w.id}"
}

@Composable
private fun DeviceTile(onPick: () -> Unit) {
    Column(
        Modifier.clip(RoundedCornerShape(14.dp)).clickable(onClick = onPick).background(MaterialTheme.colorScheme.surfaceContainerHigh).aspectRatio(9f / 16f),
        horizontalAlignment = Alignment.CenterHorizontally, verticalArrangement = Arrangement.Center,
    ) {
        Icon(Icons.Rounded.AddPhotoAlternate, null, tint = MaterialTheme.colorScheme.onSurfaceVariant)
        Text(
            stringResource(R.string.wallpaper_from_device), style = MaterialTheme.typography.labelSmall,
            color = MaterialTheme.colorScheme.onSurfaceVariant, modifier = Modifier.padding(top = 8.dp),
        )
    }
}

/** Preview dialog shared by bundled, generated and device picks. */
@Composable
private fun WallpaperDialog(
    title: String,
    thumbKey: String,
    loadThumb: suspend () -> ImageBitmap?,
    onSet: (String) -> Unit,
    onExtra: @Composable () -> Unit,
    onDismiss: () -> Unit,
) {
    Dialog(onDismissRequest = onDismiss) {
        Column(
            Modifier.clip(RoundedCornerShape(20.dp)).background(MaterialTheme.colorScheme.surfaceContainerHigh).padding(14.dp),
            verticalArrangement = Arrangement.spacedBy(8.dp),
        ) {
            WallpaperThumb(thumbKey = thumbKey, load = loadThumb, Modifier.fillMaxWidth().aspectRatio(9f / 16f))
            Text(title, style = MaterialTheme.typography.bodyMedium)
            Row(horizontalArrangement = Arrangement.spacedBy(4.dp)) {
                TextButton(onClick = { onSet("home") }) { Text(stringResource(R.string.wallpaper_set_home)) }
                TextButton(onClick = { onSet("lock") }) { Text(stringResource(R.string.wallpaper_set_lock)) }
            }
            Row(horizontalArrangement = Arrangement.spacedBy(4.dp)) {
                TextButton(onClick = { onSet("both") }) { Text(stringResource(R.string.wallpaper_set_both)) }
                onExtra()
            }
        }
    }
}

/** Sampled thumbnail; blank while loading or unreadable. */
@Composable
private fun WallpaperThumb(thumbKey: String, load: suspend () -> ImageBitmap?, modifier: Modifier = Modifier) {
    var bitmap by remember(thumbKey) { mutableStateOf<ImageBitmap?>(null) }
    LaunchedEffect(thumbKey) {
        bitmap = withContext(Dispatchers.IO) { runCatching { load() }.getOrNull() }
    }
    val shape = RoundedCornerShape(14.dp)
    if (bitmap != null) {
        Image(bitmap!!, null, modifier = modifier.clip(shape), contentScale = ContentScale.Crop)
    } else {
        Box(modifier.background(MaterialTheme.colorScheme.surfaceContainerHighest, shape))
    }
}

private fun loadBundled(context: android.content.Context): List<BundledWallpaper> = runCatching {
    val text = context.assets.open("wallpapers/catalog.json").bufferedReader().use { it.readText() }
    Json { ignoreUnknownKeys = true }.decodeFromString<List<BundledWallpaper>>(text)
}.getOrDefault(emptyList())

private fun decodeFileThumb(path: String, maxDim: Int): ImageBitmap? = runCatching {
    val bounds = BitmapFactory.Options().apply { inJustDecodeBounds = true }
    BitmapFactory.decodeFile(path, bounds)
    if (bounds.outWidth <= 0 || bounds.outHeight <= 0) return null
    var sample = 1
    while (bounds.outWidth / (sample * 2) >= maxDim || bounds.outHeight / (sample * 2) >= maxDim) sample *= 2
    BitmapFactory.decodeFile(path, BitmapFactory.Options().apply { inSampleSize = sample })?.asImageBitmap()
}.getOrNull()

private fun decodeAssetThumb(context: android.content.Context, file: String, maxDim: Int): ImageBitmap? = runCatching {
    val bytes = context.assets.open("wallpapers/$file").use { it.readBytes() }
    val bounds = BitmapFactory.Options().apply { inJustDecodeBounds = true }
    BitmapFactory.decodeByteArray(bytes, 0, bytes.size, bounds)
    if (bounds.outWidth <= 0 || bounds.outHeight <= 0) return null
    var sample = 1
    while (bounds.outWidth / (sample * 2) >= maxDim || bounds.outHeight / (sample * 2) >= maxDim) sample *= 2
    BitmapFactory.decodeByteArray(bytes, 0, bytes.size, BitmapFactory.Options().apply { inSampleSize = sample })?.asImageBitmap()
}.getOrNull()

private fun decodeUriThumb(context: android.content.Context, uri: Uri, maxDim: Int): ImageBitmap? = runCatching {    val bytes = context.contentResolver.openInputStream(uri)?.use { it.readBytes() } ?: return null
    val bounds = BitmapFactory.Options().apply { inJustDecodeBounds = true }
    BitmapFactory.decodeByteArray(bytes, 0, bytes.size, bounds)
    if (bounds.outWidth <= 0 || bounds.outHeight <= 0) return null
    var sample = 1
    while (bounds.outWidth / (sample * 2) >= maxDim || bounds.outHeight / (sample * 2) >= maxDim) sample *= 2
    BitmapFactory.decodeByteArray(bytes, 0, bytes.size, BitmapFactory.Options().apply { inSampleSize = sample })?.asImageBitmap()
}.getOrNull()

